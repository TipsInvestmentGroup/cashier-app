// Generates lib/tenancy-fks.ts: for every model, its foreign keys that point at a company-scoped model.
// The Prisma tenant guard uses it to reject a write that references ANOTHER company's record (an outlet, product,
// person, account ... of a different company). Parsed from schema.prisma because Prisma's runtime data model
// does not expose relation fields.
//
//   npx tsx scripts/gen-tenancy-fks.ts           regenerate the file
//   npx tsx scripts/gen-tenancy-fks.ts --check   fail (exit 1) if the committed file is out of date (used in CI)
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { CHILDREN, GUARDED } from '../lib/tenancy-registry'

const root = process.cwd()
const schema = readFileSync(path.join(root, 'prisma/schema.prisma'), 'utf8')
const target = path.join(root, 'lib/tenancy-fks.ts')

type Fk = { field: string; rel: string; target: string }
const map: Record<string, Fk[]> = {}

for (const m of schema.matchAll(/^model (\w+) \{([\s\S]*?)^\}/gm)) {
  const [, model, body] = m
  for (const line of body.split('\n')) {
    // e.g.   outlet   Outlet  @relation(fields: [outletId], references: [id])
    const r = line.match(/^\s*(\w+)\s+(\w+)\??\s+@relation\((?:[^)]*?)fields:\s*\[\s*(\w+)\s*\]/)
    if (!r) continue // (composite relations with several fields are not scoped by this guard)
    const [, rel, tgt, field] = r
    if (!GUARDED.has(tgt)) continue
    ;(map[model] ||= []).push({ field, rel, target: tgt })
  }
}

// shape of each guarded model's companyId column: the guard may only say `companyId: null` where it is nullable
const nullable: string[] = []
const emptyDefault: string[] = []
for (const m of schema.matchAll(/^model (\w+) \{([\s\S]*?)^\}/gm)) {
  const [, model, body] = m
  if (!GUARDED.has(model)) continue
  const f = body.match(/^\s*companyId\s+String(\??)\s*(.*)$/m)
  if (!f) continue
  if (f[1] === '?') nullable.push(model)
  else if (/@default\(""\)/.test(f[2])) emptyDefault.push(model)
}
nullable.sort(); emptyDefault.sort()

// child model -> the relation field that reaches its parent (so a directly-queried child can be scoped through it)
const childScope: Record<string, { rel: string; parent: string }> = {}
const noRelation: string[] = []
for (const m of schema.matchAll(/^model (\w+) \{([\s\S]*?)^\}/gm)) {
  const [, model, body] = m
  const parent = CHILDREN[model]
  if (!parent) continue
  let rel: string | null = null
  for (const line of body.split('\n')) {
    const r = line.match(/^\s*(\w+)\s+(\w+)\??\s+@relation\(/)
    if (r && r[2] === parent) { rel = r[1]; break }
  }
  if (rel) childScope[model] = { rel, parent }
  else noRelation.push(model)
}
noRelation.sort()

const lines: string[] = []
lines.push('// GENERATED by scripts/gen-tenancy-fks.ts from prisma/schema.prisma - do not edit by hand.')
lines.push("// model -> its foreign keys that point at a company-scoped model (see lib/tenancy-registry.ts GUARDED).")
lines.push('')
lines.push('export interface TenantFk { field: string; rel: string; target: string }')
lines.push('')
lines.push('export const TENANT_FKS: Record<string, readonly TenantFk[]> = {')
for (const model of Object.keys(map).sort()) {
  lines.push(`  ${model}: [${map[model].map((f) => `{ field: '${f.field}', rel: '${f.rel}', target: '${f.target}' }`).join(', ')}],`)
}
lines.push('}')
lines.push('')
lines.push('/** Guarded models whose companyId is OPTIONAL (may be NULL): the guard treats NULL as the original company. */')
lines.push(`export const COMPANY_NULLABLE: ReadonlySet<string> = new Set([${nullable.map((n) => `'${n}'`).join(', ')}])`)
lines.push('')
lines.push("/** Guarded models whose companyId is a required string defaulting to '' (the pre-multi-company 'no company'). */")
lines.push(`export const COMPANY_EMPTY_DEFAULT: ReadonlySet<string> = new Set([${emptyDefault.map((n) => `'${n}'`).join(', ')}])`)
lines.push('')
lines.push('/** Child model -> the relation reaching its parent. A directly-queried child is scoped through it (parent chain resolved recursively). */')
lines.push('export const CHILD_SCOPE: Record<string, { rel: string; parent: string }> = {')
for (const k of Object.keys(childScope).sort()) lines.push(`  ${k}: { rel: '${childScope[k].rel}', parent: '${childScope[k].parent}' },`)
lines.push('}')
lines.push('')
lines.push('/** Children with NO relation field to their parent (a plain id column): they cannot be scoped by the guard and must be reached through the parent. */')
lines.push(`export const CHILDREN_WITHOUT_RELATION: readonly string[] = [${noRelation.map((n) => `'${n}'`).join(', ')}]`)
lines.push('')
const out = lines.join('\n')

if (process.argv.includes('--check')) {
  let current = ''
  try { current = readFileSync(target, 'utf8').replace(/\r\n/g, '\n') } catch { /* missing */ }
  if (current !== out) { console.error('[gen-tenancy-fks] lib/tenancy-fks.ts is out of date - run: npx tsx scripts/gen-tenancy-fks.ts'); process.exit(1) }
  console.log(`[gen-tenancy-fks] OK - ${Object.keys(map).length} models with scoped foreign keys`)
} else {
  writeFileSync(target, out)
  console.log(`[gen-tenancy-fks] wrote lib/tenancy-fks.ts (${Object.keys(map).length} models, ${Object.values(map).reduce((n, v) => n + v.length, 0)} foreign keys)`)
}
